//! Embeds the built web app in the daemon (layout rust-control-plane.md 8.1; frontend-and-plugins.md 8.8). The app is
//! `apps/web/dist/`, built by `just web-embed`. This script writes a table of `include_bytes!`, one row per file, so
//! the daemon serves the app with no file read at run time. When the app hasn't been built, a placeholder page takes
//! its place, so `cargo build` and the tests never need Node.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

/// The web app's build folder, relative to this crate (the workspace's apps/web).
const WEB_DIST_FROM_CRATE: &str = "../../apps/web/dist";
/// The index page's file name: the app's entry point, served at "/" and "/index.html".
const INDEX_FILE: &str = "index.html";
/// The table the daemon includes from OUT_DIR (web_assets.rs).
const TABLE_FILE: &str = "web_assets_table.rs";
/// The page served when the app isn't built: it says how to build it, and nothing else.
const PLACEHOLDER_PAGE: &str = "<!doctype html>\n<meta charset=\"utf-8\">\n<title>Rastai</title>\n\
    <p>The web app isn't built into this daemon. Run <code>just web-embed</code> and build again.</p>\n";
const PLACEHOLDER_FILE: &str = "placeholder-index.html";

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let manifest_dir = PathBuf::from(required_env("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(required_env("OUT_DIR"));
    let dist = manifest_dir.join(WEB_DIST_FROM_CRATE);
    println!("cargo:rerun-if-changed={}", dist.display());
    let mut files = Vec::new();
    if dist.join(INDEX_FILE).is_file() {
        collect_files(&dist, &dist, &mut files);
    } else {
        let placeholder = out_dir.join(PLACEHOLDER_FILE);
        write_or_fail(&placeholder, PLACEHOLDER_PAGE.as_bytes());
        files.push(("/index.html".to_string(), placeholder));
    }
    files.sort();
    write_or_fail(&out_dir.join(TABLE_FILE), table_source(&files).as_bytes());
}

/// Every file under `folder`, as (its URL path, its absolute path), in a folder walk.
fn collect_files(root: &Path, folder: &Path, files: &mut Vec<(String, PathBuf)>) {
    let entries = match fs::read_dir(folder) {
        Ok(entries) => entries,
        Err(error) => fail(&format!("can't read {}: {error}", folder.display())),
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_files(root, &path, files);
        } else if let Ok(relative) = path.strip_prefix(root) {
            let url_path = format!("/{}", relative.to_string_lossy().replace('\\', "/"));
            files.push((url_path, path));
        }
    }
}

/// The Rust source of the table: one WebAsset per file, with its type from its extension.
fn table_source(files: &[(String, PathBuf)]) -> String {
    let mut source = String::from("// Generated by build.rs from apps/web/dist/. Do not edit.\n");
    source.push_str("pub static WEB_ASSETS: &[WebAsset] = &[\n");
    for (url_path, file) in files {
        source.push_str(&format!(
            "    WebAsset {{ path: {:?}, content_type: {:?}, bytes: include_bytes!({:?}) }},\n",
            url_path,
            content_type_of(url_path),
            file.display().to_string(),
        ));
    }
    source.push_str("];\n");
    source
}

/// The type a file is served as, from its extension. A browser runs a script only when it is one of these types.
fn content_type_of(url_path: &str) -> &'static str {
    let extension = url_path.rsplit('.').next().unwrap_or("");
    match extension {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" | "map" => "application/json",
        "wasm" => "application/wasm",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "ico" => "image/x-icon",
        "txt" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}

fn required_env(name: &str) -> String {
    match env::var(name) {
        Ok(value) => value,
        Err(error) => fail(&format!("cargo didn't set {name}: {error}")),
    }
}

fn write_or_fail(path: &Path, bytes: &[u8]) {
    if let Err(error) = fs::write(path, bytes) {
        fail(&format!("can't write {}: {error}", path.display()));
    }
}

/// A build script can't return an error, so a broken build stops with the reason.
fn fail(reason: &str) -> ! {
    panic!("rastai-server's build.rs: {reason}");
}
