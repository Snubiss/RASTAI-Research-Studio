"""check-fuzz-locks on fixture fuzz workspaces whose lock is current, stale and missing a crate (contracts 12.5).

The fixtures have no registry dependencies, only a path dependency on their crate, so cargo resolves them offline.
"""

# A crate and its cargo-fuzz workspace, the shape of crates/<crate>/fuzz/ in the repository.
SAMPLE_CRATE_MANIFEST = '[package]\nname = "sample"\nversion = "0.1.0"\nedition = "2024"\n'
SAMPLE_FUZZ_MANIFEST = (
    '[package]\nname = "sample-fuzz"\nversion = "0.0.0"\nedition = "2024"\n\n'
    '[dependencies]\nsample = { path = ".." }\n\n'
    '[workspace]\nmembers = ["."]\n'
)
# The lock cargo writes for SAMPLE_FUZZ_MANIFEST.
LOCK_HEADER = (
    "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n"
)
CURRENT_LOCK = (
    LOCK_HEADER + '[[package]]\nname = "sample"\nversion = "0.1.0"\n\n'
    '[[package]]\nname = "sample-fuzz"\nversion = "0.0.0"\ndependencies = [\n "sample",\n]\n'
)
# The lock from before the fuzz crate depended on its crate: what a dependency change without a refresh leaves.
STALE_LOCK = LOCK_HEADER + '[[package]]\nname = "sample-fuzz"\nversion = "0.0.0"\n'


def sample_tree(lock_text: str) -> dict[str, str]:
    return {
        "crates/sample/Cargo.toml": SAMPLE_CRATE_MANIFEST,
        "crates/sample/src/lib.rs": "",
        "crates/sample/fuzz/Cargo.toml": SAMPLE_FUZZ_MANIFEST,
        "crates/sample/fuzz/src/lib.rs": "",
        "crates/sample/fuzz/Cargo.lock": lock_text,
    }


def test_current_lock_passes(write_tree, run_check):
    root = write_tree(sample_tree(CURRENT_LOCK))
    result = run_check("check-fuzz-locks", "--root", str(root))
    assert result.returncode == 0, result.stdout
    assert (root / "crates/sample/fuzz/Cargo.lock").read_text() == CURRENT_LOCK


def test_stale_lock_fails_and_is_left_alone(write_tree, run_check):
    root = write_tree(sample_tree(STALE_LOCK))
    result = run_check("check-fuzz-locks", "--root", str(root))
    assert result.returncode == 1
    assert "crates/sample/fuzz/Cargo.lock: out of date with its manifests; refresh it with" in result.stdout
    assert "1 problem(s)" in result.stdout
    # --locked: the check reports a stale lock, it never rewrites it.
    assert (root / "crates/sample/fuzz/Cargo.lock").read_text() == STALE_LOCK


def test_a_manifest_cargo_cannot_read_fails(write_tree, run_check):
    files = sample_tree(CURRENT_LOCK)
    files["crates/sample/fuzz/Cargo.toml"] = "[package\n"
    root = write_tree(files)
    result = run_check("check-fuzz-locks", "--root", str(root))
    assert result.returncode == 1
    assert "crates/sample/fuzz/Cargo.lock: cargo couldn't resolve the workspace:" in result.stdout


def test_the_real_repository_passes(run_check):
    result = run_check("check-fuzz-locks")
    assert result.returncode == 0, result.stdout
